/**
 * Who should receive a notification.
 *
 * Every active user in the company except the person who caused it. Being sent
 * a notification about your own action is the fastest way to make people ignore
 * the badge entirely.
 *
 * A null actor means there is nobody to exclude - the recurring journal
 * scheduler generates documents as 'SYSTEM (Recurring)' - so everyone gets it.
 *
 * Recipients are every active user in the tenant database. There is no
 * user-to-company table to filter on (`master_user` carries only
 * mu_id/fullname/username/password/access_id/status/email), and each tenant
 * database holds one company, so the pool itself is the company boundary. The
 * company_id on the notification row is what scopes the *read* side.
 *
 * Deliberately not filtered by route access: a receipt being approved matters to
 * a supervisor whose plan does not include receipts.
 */
const listRecipientIds = async ({ excludeUserId, dbName }) => {
  let sql = `SELECT mu_id FROM master_user WHERE mu_status = 'active'`
  const params = []
  if (excludeUserId !== null && excludeUserId !== undefined) {
    sql += ' AND mu_id <> ?'
    params.push(Number(excludeUserId))
  }
  const rows = await q(sql, params, dbName)
  return (rows || []).map((r) => Number(r.mu_id)).filter((id) => Number.isInteger(id) && id > 0)
}

/**
 * Create a notification and push it to the sockets of everyone who should see
 * it.
 *
 * The row is written first and pushed second: a client that misses the push
 * still has the row waiting when it next loads, so a dropped socket degrades to
 * "the badge is right on refresh" rather than "the notification vanished".
 */
const createAndNotify = async (input) => {
  const v = normaliseCreate(input)
  // Resolved here rather than only inside createNotification, because the push
  // payload is built from this copy of the validated event and must carry the
  // same deep link that gets stored. createNotification is handed the resolved
  // link so the lookup is not repeated.
  v.link = await buildDeepLink({
    link: v.link,
    module: v.module,
    entityId: v.entityId,
    dbName: input.dbName,
  })
  const created = await createNotification({ ...input, link: v.link })
  if (!created.id || created.duplicate) return { ...created, pushed: 0 }

  const recipients = await listRecipientIds({ excludeUserId: v.actorUserId, dbName: input.dbName })
  if (recipients.length === 0) return { ...created, pushed: 0, recipients: 0 }

  // Built from the validated input rather than read back, so the payload cannot
  // disagree with what was validated and no extra query is needed.
  const notification = {
    id: created.id,
    companyId: v.companyId,
    type: v.type,
    module: v.module,
    severity: v.severity,
    title: v.title,
    body: v.body,
    link: v.link,
    entityType: v.entityType,
    entityId: v.entityId,
    actorUserId: v.actorUserId,
    actorName: v.actorName,
    changes: v.changes,
    createdAt: new Date().toISOString(),
    expiresAt: v.expiresAt,
    // Every recipient of this push is by definition someone who has not read it.
    isRead: false,
  }

  const pushed = pushToUsers(input.dbName, recipients, 'notification:new', {
    notification,
    // The client owns its own user id, so it attaches read state on arrival.
    unreadFor: recipients,
  })

  return { ...created, pushed, recipients: recipients.length }
}

/**
 * Turn the document controllers' audit strings into a structured change list.
 *
 * Every mutation handler already builds a human-readable diff for the audit
 * trail, in a consistent shape:
 *
 *     `Doc Ref: ${from || 'NULL'} \u2192 ${to || 'NULL'}`
 *     `Added new attachment: ${name}`
 *
 * Rather than diff the request bodies - which are full-row, and in at least one
 * module name fields that are not columns at all - these strings are reused. The
 * controller has already compared old against new and thrown away everything
 * that did not change, which is the harder half of the work.
 *
 * Entries without an arrow (an attachment added, an item deleted) carry no
 * before/after, so they become a note. The UI shows the note as-is rather than
 * rendering empty from/to boxes.
 *
 * Shared across modules, because the audit format is identical in each of them.
 */
const ARROW = '\u2192'

const parseAuditChanges = (changes) => {
  if (!Array.isArray(changes)) return null
  const out = []
  for (const raw of changes) {
    // A caller may already have a structured change - the status handlers pass
    // `{ field: 'state', from, to }` directly when there was no audit text.
    // Passing it through String() would turn it into "[object Object]".
    if (raw && typeof raw === 'object') {
      if (raw.field || raw.note) out.push(raw)
      continue
    }

    const text = String(raw ?? '').trim()
    if (!text) continue

    // Last colon wins, so `Item 12 Resp Center: a → b` splits on the right one.
    const colon = text.indexOf(':')
    if (colon > 0 && text.includes(ARROW)) {
      const field = text.slice(0, colon).trim()
      const rest = text.slice(colon + 1)
      const at = rest.indexOf(ARROW)
      const from = rest.slice(0, at).trim()
      const to = rest.slice(at + ARROW.length).trim()
      out.push({
        field,
        from: from === 'NULL' ? null : from,
        to: to === 'NULL' ? null : to,
      })
    } else {
      out.push({ field: null, note: text })
    }
  }
  return out.length > 0 ? out : null
}

