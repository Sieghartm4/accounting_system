/**
 * The list for one reader.
 *
 * `filter` is 'unread', 'read' or 'all'. Read state comes from the join, so the
 * badge and the list can never disagree.
 */
const listForUser = async ({ companyId, userId, filter = 'all', limit = 50, dbName }) => {
  const cap = Math.min(Math.max(Number(limit) || 50, 1), 200)

  const readClause =
    filter === 'unread'
      ? 'AND r.nr_id IS NULL'
      : filter === 'read'
        ? 'AND r.nr_id IS NOT NULL'
        : filter === 'all'
          ? ''
          : null
  if (readClause === null) throw httpError('unknown filter', 'VALIDATION', 400)

  // Your own actions are not in your bell. The push already excludes the actor,
  // so listing the row here would give a badge counting notifications that never
  // arrived. A null actor is a system notification and belongs to everyone.
  const notMine = `(nt.${n.selectOptionColumns.actor_user_id} IS NULL
             OR nt.${n.selectOptionColumns.actor_user_id} <> ?)`

  // `nt.*` alone does not carry the join's marker, so isRead would be false for
  // every row. The marker is selected under its own name because `nt` and `r`
  // are the only two tables in play and neither owns it.
  const sql = `
    SELECT nt.*, r.${nr.selectOptionColumns.id} AS read_marker
      FROM ${n.tablename} nt
      LEFT JOIN ${nr.tablename} r
        ON r.${nr.selectOptionColumns.notification_id} = nt.${n.selectOptionColumns.id}
       AND r.${nr.selectOptionColumns.user_id} = ?
      WHERE nt.${n.selectOptionColumns.company_id} = ?
        AND (nt.${n.selectOptionColumns.expires_at} IS NULL
             OR nt.${n.selectOptionColumns.expires_at} > NOW())
        AND ${notMine}
        ${readClause}
      ORDER BY nt.${n.selectOptionColumns.created_at} DESC, nt.${n.selectOptionColumns.id} DESC
      LIMIT ${cap}`

  // Positional parameters, in the order the placeholders appear: the join's
  // reader id, then the company, then the reader again for the actor exclusion.
  const rows = await q(sql, [userId, companyId, userId], dbName)
  return (rows || []).map((row) => ({
    ...rowToNotification(row),
    isRead: row.read_marker !== null && row.read_marker !== undefined,
  }))
}

/**
 * How many this reader has not read.
 *
 * Counted over the same join and the same expiry rule as the list, so the badge
 * matches what the dropdown would show.
 */
const unreadCount = async ({ companyId, userId, dbName }) => {
  const sql = `
    SELECT COUNT(*) AS total
      FROM ${n.tablename} nt
      LEFT JOIN ${nr.tablename} r
        ON r.${nr.selectOptionColumns.notification_id} = nt.${n.selectOptionColumns.id}
       AND r.${nr.selectOptionColumns.user_id} = ?
      WHERE nt.${n.selectOptionColumns.company_id} = ?
        AND r.${nr.selectOptionColumns.id} IS NULL
        AND (nt.${n.selectOptionColumns.expires_at} IS NULL
             OR nt.${n.selectOptionColumns.expires_at} > NOW())
        AND (nt.${n.selectOptionColumns.actor_user_id} IS NULL
             OR nt.${n.selectOptionColumns.actor_user_id} <> ?)`

  const rows = await q(sql, [userId, companyId, userId], dbName)
  return Number(rows?.[0]?.total || 0)
}

/**
 * Unread counts grouped by module.
 *
 * Used to show badges on sidebar navigation items.
 */
const unreadCountByModule = async ({ companyId, userId, dbName }) => {
  const sql = `
    SELECT nt.${n.selectOptionColumns.module}, COUNT(*) AS total
      FROM ${n.tablename} nt
      LEFT JOIN ${nr.tablename} r
        ON r.${nr.selectOptionColumns.notification_id} = nt.${n.selectOptionColumns.id}
       AND r.${nr.selectOptionColumns.user_id} = ?
      WHERE nt.${n.selectOptionColumns.company_id} = ?
        AND r.${nr.selectOptionColumns.id} IS NULL
        AND (nt.${n.selectOptionColumns.expires_at} IS NULL
             OR nt.${n.selectOptionColumns.expires_at} > NOW())
        AND (nt.${n.selectOptionColumns.actor_user_id} IS NULL
             OR nt.${n.selectOptionColumns.actor_user_id} <> ?)
      GROUP BY nt.${n.selectOptionColumns.module}`

  const rows = await q(sql, [userId, companyId, userId], dbName)
  const result = {}
  for (const row of rows || []) {
    const module = row[n.selectOptionColumns.module]
    if (module) {
      result[module] = Number(row.total || 0)
    }
  }
  return result
}

/**
 * Mark one notification read for one reader.
 *
 * Idempotent: the unique key on (notification, user) makes a second call a
 * no-op, so a double click cannot create duplicates.
 *
 * @returns {{id:number, alreadyRead:boolean}}
 */
const markRead = async ({ companyId, userId, notificationId, dbName }) => {
  const id = Number(notificationId)
  if (!Number.isInteger(id) || id <= 0) {
    throw httpError('notificationId must be a positive integer', 'VALIDATION', 400)
  }

  // Scoped to the company on both sides, so an id from another company cannot be
  // marked read by guessing.
  const rows = await q(
    `SELECT ${n.selectOptionColumns.id}
       FROM ${n.tablename}
      WHERE ${n.selectOptionColumns.id} = ?
        AND ${n.selectOptionColumns.company_id} = ?
      LIMIT 1`,
    [id, companyId],
    dbName,
  )
  if (!rows || rows.length === 0) {
    throw httpError('Notification not found', 'NOT_FOUND', 404)
  }

  const result = await q(
    `INSERT INTO ${nr.tablename}
       (${nr.selectOptionColumns.notification_id}, ${nr.selectOptionColumns.company_id},
        ${nr.selectOptionColumns.user_id})
     VALUES (?, ?, ?)
     ON DUPLICATE KEY UPDATE ${nr.tablename}.${nr.selectOptionColumns.read_at} = ${nr.tablename}.${nr.selectOptionColumns.read_at}`,
    [id, companyId, userId],
    dbName,
  )

  return { id, alreadyRead: !(result && (result.insertId || result.insert_id)) }
}

/**
 * Mark every unread notification in one module read, for this reader only.
 *
 * This is what clears a sidebar badge when someone opens the screen it belongs
 * to. The alternatives were worse: leaving the badge up until each item was
 * clicked made the number unreadable, because opening Receipts does not mean you
 * clicked each of the five receipts you now have to approve.
 *
 * Same rules as markAllRead - the reader's own actions are skipped and expired
 * rows are ignored - so this cannot quietly mark somebody's own work as read.
 */
const markModuleRead = async ({ companyId, userId, module, dbName }) => {
  const target = String(module ?? '').trim()
  if (!target) throw httpError('module is required', 'VALIDATION', 400)
  if (target.length > 40) throw httpError('module is too long', 'VALIDATION', 400)

  const sql = `
    INSERT INTO ${nr.tablename}
      (${nr.selectOptionColumns.notification_id}, ${nr.selectOptionColumns.company_id},
       ${nr.selectOptionColumns.user_id})
    SELECT nt.${n.selectOptionColumns.id}, nt.${n.selectOptionColumns.company_id}, ?
      FROM ${n.tablename} nt
      LEFT JOIN ${nr.tablename} r
        ON r.${nr.selectOptionColumns.notification_id} = nt.${n.selectOptionColumns.id}
       AND r.${nr.selectOptionColumns.user_id} = ?
     WHERE nt.${n.selectOptionColumns.company_id} = ?
       AND nt.${n.selectOptionColumns.module} = ?
       AND r.${nr.selectOptionColumns.id} IS NULL
       AND (nt.${n.selectOptionColumns.expires_at} IS NULL
            OR nt.${n.selectOptionColumns.expires_at} > NOW())
       AND (nt.${n.selectOptionColumns.actor_user_id} IS NULL
            OR nt.${n.selectOptionColumns.actor_user_id} <> ?)
    ON DUPLICATE KEY UPDATE ${nr.tablename}.${nr.selectOptionColumns.read_at} = ${nr.tablename}.${nr.selectOptionColumns.read_at}`

  const result = await q(sql, [userId, userId, companyId, target, userId], dbName)
  return { module: target, cleared: result?.affectedRows ?? 0 }
}

