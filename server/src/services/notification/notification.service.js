/**
 * Notifications, and per-user read state.
 *
 * ## The read rule
 *
 * A notification belongs to the company; whether *you* have read it belongs to
 * you. Read state is therefore a row in `notification_reads` keyed by
 * (notification, user), never a flag on the notification. One person opening a
 * notification cannot remove it from anyone else.
 *
 *     unread(n, u)  <=>  NOT EXISTS (read row for n and u)
 *
 * Every read query therefore LEFT JOINs the reads table on the reader's own id.
 * That join is the only place read state is decided, so there is one rule rather
 * than a count computed one way for the list and another for the badge.
 *
 * ## Company scope
 *
 * Each company has its own database, so tenant isolation comes from the pool.
 * A tenant can still hold several companies in `master_company`, so company_id
 * is carried on both tables and always filtered on. The controller verifies the
 * id belongs to the caller before reaching here.
 */

const n = Accounting.notifications
const nr = Accounting.notification_reads

const SEVERITIES = new Set(['info', 'warning', 'critical'])

/**
 * Run a statement against the caller's tenant database.
 *
 * This wrapper exists because omitting the tenant argument is not a neutral
 * default. `Query` falls back to `getTenantPool()` with no name, which resolves
 * to the process-global default database (`subscription`) rather than the tenant
 * that owns the document. Reads and writes then succeed against the wrong
 * database, which looks like a working system with no notifications rather than
 * an error - so every statement in this module goes through here and refuses to
 * run without a tenant.
 */
const q = async (sql, params, dbName) => {
  if (!dbName) {
    throw httpError('dbName is required for notification queries', 'TENANT_REQUIRED', 500)
  }
  return Query(sql, params, null, null, dbName)
}

/** Reject a bad payload at the boundary rather than writing a half-formed row. */
const normaliseCreate = (input) => {
  const title = String(input.title ?? '').trim()
  if (!title) throw httpError('title is required', 'VALIDATION', 400)
  if (title.length > 200) throw httpError('title is too long', 'VALIDATION', 400)

  const severity = String(input.severity ?? 'info')
  if (!SEVERITIES.has(severity)) throw httpError('unknown severity', 'VALIDATION', 400)

  const type = String(input.type ?? '').trim()
  if (!type) throw httpError('type is required', 'VALIDATION', 400)
  if (type.length > 40) throw httpError('type is too long', 'VALIDATION', 400)

  if (!Number.isInteger(input.companyId) || input.companyId <= 0) {
    throw httpError('companyId is required', 'VALIDATION', 400)
  }

  // Actor is optional. A recurring journal generated by the scheduler has no
  // user behind it, and writing the literal 'SYSTEM (Recurring)' into an id
  // column would be a lie the code could not act on.
  let actorUserId = null
  if (input.actorUserId !== null && input.actorUserId !== undefined) {
    const id = Number(input.actorUserId)
    if (!Number.isInteger(id) || id <= 0) {
      throw httpError('actorUserId must be a positive integer', 'VALIDATION', 400)
    }
    actorUserId = id
  }

  const dedupeKey = input.dedupeKey ? String(input.dedupeKey).slice(0, 190) : null

  return {
    companyId: input.companyId,
    type,
    module: input.module ? String(input.module).slice(0, 40) : null,
    severity,
    title,
    body: input.body ? String(input.body) : null,
    link: input.link ? String(input.link).slice(0, 255) : null,
    entityType: input.entityType ? String(input.entityType).slice(0, 40) : null,
    entityId:
      input.entityId === null || input.entityId === undefined
        ? null
        : String(input.entityId).slice(0, 80),
    actorUserId,
    actorName: input.actorName ? String(input.actorName).slice(0, 300) : null,
    changes: input.changes ?? null,
    dedupeKey,
    expiresAt: input.expiresAt || null,
  }
}

/**
 * Module -> the route its page lives at.
 *
 * Matches the routeMap the header search uses when it opens a document, so a
 * notification and a search result land on the same screen.
 */
const MODULE_ROUTES = {
  receipts: 'receipts',
  sales: 'sales',
  purchase: 'purchase',
  collection: 'collections',
  disbursement: 'disbursement',
  payments: 'payments',
  adjustments: 'adjustments',
  purchase_order: 'purchase_order',
  recurring_journals: 'recurring_journals',
}

/**
 * Module -> where its document reference and numeric id live.
 *
 * The controllers pass the *document reference* ("PO-101626-0002") because that
 * is what they title the notification with. But the module pages fetch a single
 * document with `GET /receipt/{id}` keyed on the numeric row id, the same value
 * the header search passes. Linking with the reference therefore opened nothing.
 *
 * Resolved here rather than at each of the ~28 call sites: one place, and every
 * module cannot drift from the search routeMap.
 */
const MODULE_TABLES = {
  receipts: { table: 'receipts', ref: 'r_document_reference', id: 'r_id' },
  sales: { table: 'sales', ref: 's_document_reference', id: 's_id' },
  purchase: { table: 'purchase', ref: 'p_document_reference', id: 'p_id' },
  collection: { table: 'collections', ref: 'c_document_reference', id: 'c_id' },
  disbursement: {
    table: 'cash_disbursements',
    ref: 'cd_document_reference',
    id: 'cd_id',
  },
  payments: { table: 'payments', ref: 'c_document_reference', id: 'c_id' },
  adjustments: { table: 'adjustments', ref: 'a_document_reference', id: 'a_id' },
  purchase_order: { table: 'purchase_order', ref: 'po_reference', id: 'po_id' },
}

/**
 * The primary key for a document, from either form.
 *
 * Two forms reach here and neither can be assumed: the controllers title with
 * the document reference ("PO-101626-0002") while some tables - receipts, for
 * one - key the row on that same reference and others key on a plain number.
 * A "looks numeric, so it must be the id" shortcut therefore resolves the wrong
 * document for whichever table happens to use numeric references.
 *
 * So both columns are matched and the exact primary-key hit wins, in one
 * indexed lookup.
 *
 * @returns {Promise<string|null>} null when the document cannot be resolved, so
 *          the caller can fall back to the module page rather than link nowhere.
 */
const resolveDocumentId = async ({ module, entityId, dbName }) => {
  if (entityId === null || entityId === undefined) return null
  const value = String(entityId).trim()
  // A whitespace-only reference is not a reference.
  if (!value) return null

  const target = MODULE_TABLES[module]
  // Nothing to map against, so the id cannot be trusted. The caller falls back to
  // the module page rather than linking to a document that may not exist.
  if (!target) return null

  try {
    // Two rows are fetched deliberately. An exact primary-key hit is
    // unambiguous; a reference is not, because document references are not
    // unique in practice - one tenant here has the same reference eight times -
    // and guessing would open the wrong document.
    const rows = await q(
      `SELECT ${target.id}
         FROM ${target.table}
        WHERE ${target.id} = ? OR TRIM(${target.ref}) = ?
        LIMIT 2`,
      [value, value],
      dbName,
    )
    if (!rows || rows.length === 0) return null

    const exact = rows.filter((row) => String(row[target.id]) === value)
    if (exact.length > 0) return String(exact[0][target.id])

    if (rows.length > 1) {
      // The reference matches more than one document. Linking to either would be
      // a coin flip, so the caller gets the module page instead.
      return null
    }
    return String(rows[0][target.id])
  } catch (err) {
    // A failed lookup must not cost the notification - the link just falls back
    // to the module page, which still shows the document in its list.
    console.error('[notify] could not resolve document id:', err?.message || err)
    return null
  }
}

/**
 * Build a link that opens the document, not just its module.
 *
 * `/purchase` opens the list; `/purchase?id=42` opens that purchase in view
 * mode, which is what the header search does and what a notification about a
 * specific document should do.
 *
 * Falls back to the module page whenever the id cannot be resolved, so the
 * worst case is the old behaviour rather than a dead link.
 */
const buildDeepLink = async ({ link, module, entityId, dbName }) => {
  const route = MODULE_ROUTES[module]
  const base = link || (route ? `/${route}` : null)
  if (!base) return null
  // Already deep, or explicitly authored - leave it alone.
  if (/[?&]id=/.test(base)) return base

  const documentId = await resolveDocumentId({ module, entityId, dbName })
  if (!documentId) return base

  return `${base}${base.includes('?') ? '&' : '?'}id=${encodeURIComponent(documentId)}`
}

function httpError(message, code, status) {
  const err = new Error(message)
  err.code = code
  err.status = status
  return err
}

/**
 * Create one notification.
 * @returns {{id:number, duplicate:boolean}}
 */
const createNotification = async (input) => {
  const v = normaliseCreate(input)
  // Deep link, resolved once here so both the stored row and the pushed payload
  // carry it.
  v.link = await buildDeepLink({
    link: v.link,
    module: v.module,
    entityId: v.entityId,
    dbName: input.dbName,
  })

  const params = [
    v.companyId,
    v.type,
    v.module,
    v.severity,
    v.title,
    v.body,
    v.link,
    v.entityType,
    v.entityId,
    v.actorUserId,
    v.actorName,
    v.changes === null ? null : JSON.stringify(v.changes),
    v.dedupeKey,
    v.expiresAt,
  ]

  // INSERT ... ON DUPLICATE KEY UPDATE on the dedupe key returns the existing
  // row instead of failing, so a nightly scheduler re-evaluating the same
  // condition is harmless. Notifications with no dedupe key keep the NULLs
  // distinct and always insert.
  const sql = `
    INSERT INTO ${n.tablename}
      (${n.selectOptionColumns.company_id}, ${n.selectOptionColumns.type},
       ${n.selectOptionColumns.module}, ${n.selectOptionColumns.severity},
       ${n.selectOptionColumns.title}, ${n.selectOptionColumns.body},
       ${n.selectOptionColumns.link}, ${n.selectOptionColumns.entity_type},
       ${n.selectOptionColumns.entity_id}, ${n.selectOptionColumns.actor_user_id},
       ${n.selectOptionColumns.actor_name}, ${n.selectOptionColumns.changes},
       ${n.selectOptionColumns.dedupe_key}, ${n.selectOptionColumns.expires_at})
    VALUES (?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?)
    ON DUPLICATE KEY UPDATE ${n.selectOptionColumns.id} = ${n.selectOptionColumns.id}`

  const result = await q(sql, params, input.dbName)
  const id = result && (result.insertId || result.insert_id)
  return { id: id ?? null, duplicate: !id }
}

