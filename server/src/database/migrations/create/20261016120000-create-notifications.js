/**
 * Notifications, and who has read them.
 *
 * ## Why two tables
 *
 * A notification is a fact about the business - a receipt was created, a filing
 * deadline is near - and it is shared by everyone in the company. Whether a
 * given person has seen it is a fact about that person, not about the
 * notification. Putting a `read` boolean on the notification would make the
 * first person to read it remove it for everyone, which is the opposite of what
 * is wanted.
 *
 * So `notifications` holds the event and `notification_reads` holds one row per
 * (notification, user). Unread for a user means no read row exists for them:
 *
 *     unread(n, u)  <=>  NOT EXISTS (SELECT 1 FROM notification_reads
 *                              WHERE notification_id = n.id AND user_id = u)
 *
 * The unique key on (notification, user) is what keeps marking read idempotent,
 * so a double click cannot create two rows or inflate a count.
 *
 * ## Scoping
 *
 * Each company is its own database, so tenant isolation is free. A tenant
 * database can still hold more than one company in `master_company`, so
 * company_id is carried explicitly and verified by the controller rather than
 * inferred - the same reason tax.controller.js resolves it instead of trusting
 * the caller.
 *
 * ## Actor
 *
 * `nt_actor_user_id` is nullable because some notifications have no human actor,
 * notably recurring journals generated by the scheduler, which writes the literal
 * 'SYSTEM (Recurring)'. Suppressing an actor from their own notification is the
 * whole point of tracking them separately from the actor's name.
 */
